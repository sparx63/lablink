function eq(
  partial: Omit<Equipment, "status" | "conditionNotes" | "quantity" | "borrowable"> & {
    status?: Equipment["status"];
    conditionNotes?: string;
    quantity?: number;
    borrowable?: boolean;
    units?: Equipment["units"];
    accessoryChecklist?: Equipment["accessoryChecklist"];
  }
): Equipment {
  return {
    status: "AVAILABLE",
    conditionNotes: "Inspected and ready.",
    quantity: 1,
    borrowable: false,
    ...partial,
  };
}

function makeUnits(prefix: string, count: number): NonNullable<Equipment["units"]> {
  return Array.from({ length: count }, (_, i) => ({
    id: `${prefix}-u${i + 1}`,
    serial: `${prefix.toUpperCase()}-SN-${String(i + 1).padStart(3, "0")}`,
    tag: `${prefix.toUpperCase()}-${String(i + 1).padStart(2, "0")}`,
    status: "AVAILABLE" as const,
    condition: "Good",
  }));
}

